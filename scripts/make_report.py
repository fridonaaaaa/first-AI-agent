"""
Generate EVAL_REPORT.md tables from saved result JSON files.

Numbers are NEVER typed by hand — they come from the result files produced
by eval_retrieval.py and eval_rag.py. Running this script again regenerates
the report identically from the same result files.

Usage:
    python scripts/make_report.py --split test

Reads from eval/results/*.json and writes docs/EVAL_REPORT.md.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT      = pathlib.Path(__file__).parent.parent
RESULTS   = ROOT / "eval" / "results"
REPORT    = ROOT / "docs" / "EVAL_REPORT.md"


def _load_result(path: pathlib.Path) -> dict:
    return json.loads(path.read_text())


def _retrieval_table(rows: list[dict]) -> str:
    header = "| Config | Name | Recall@K | MRR | K | Split |\n"
    sep    = "|---|---|---|---|---|---|\n"
    lines  = [header, sep]
    for r in rows:
        cfg = r["config"]
        lines.append(
            f"| {cfg['config_id']} | {cfg['name']} "
            f"| {r['recall_at_k']:.3f} | {r['mrr']:.3f} "
            f"| {r['top_k']} | {r['split']} |\n"
        )
    return "".join(lines)


def _rag_table(rows: list[dict]) -> str:
    header = "| Config | Name | F1 | EM | Cite-P | Abstain-Acc | n | Split |\n"
    sep    = "|---|---|---|---|---|---|---|---|\n"
    lines  = [header, sep]
    for r in rows:
        cfg = r["config"]
        lines.append(
            f"| {cfg['config_id']} | {cfg['name']} "
            f"| {r['answer_f1']:.3f} | {r['exact_match']:.3f} "
            f"| {r['citation_precision']:.3f} | {r['abstention_accuracy']:.3f} "
            f"| {r['n']} | {r['split']} |\n"
        )
    return "".join(lines)


def _error_analysis(rag_results: list[dict]) -> str:
    """List questions where F1 < 0.3 as concrete failing examples."""
    lines = []
    for r in rag_results:
        for q in r.get("per_question", []):
            if q.get("error") or q.get("f1", 1.0) < 0.3:
                lines.append(
                    f"- **{q['id']}** ({q.get('type','?')}): "
                    f"Q: *{q.get('question','')[:80]}* | "
                    f"Gold: `{q.get('gold','')[:40]}` | "
                    f"Pred: `{q.get('answer','')[:60]}` | "
                    f"F1={q.get('f1',0):.2f}\n"
                )
    if not lines:
        return "_No failing examples found._\n"
    return "".join(lines[:20])  # cap at 20 for readability


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--split", default="test", choices=["dev", "test"])
    args = parser.parse_args()

    retrieval_results = sorted(RESULTS.glob(f"*_{args.split}_retrieval.json"))
    rag_results       = sorted(RESULTS.glob(f"*_{args.split}_rag.json"))

    if not retrieval_results and not rag_results:
        print(f"No result files found in {RESULTS} for split={args.split}.")
        print("Run eval_retrieval.py and eval_rag.py first.")
        sys.exit(1)

    ret_rows = [_load_result(p) for p in retrieval_results]
    rag_rows = [_load_result(p) for p in rag_results]

    sections = [
        "# EVAL_REPORT.md\n\n",
        "_Generated by scripts/make_report.py — do not edit by hand._\n\n",
        f"**Split:** {args.split}\n\n",
    ]

    if ret_rows:
        sections += ["## Retrieval metrics\n\n", _retrieval_table(ret_rows), "\n"]

    if rag_rows:
        sections += ["## RAG pipeline metrics\n\n", _rag_table(rag_rows), "\n"]
        sections += ["## Error analysis — low-F1 questions\n\n", _error_analysis(rag_rows), "\n"]

    sections += [
        "## Metric definitions\n\n",
        "| Metric | Definition |\n",
        "|---|---|\n",
        "| Recall@K | Fraction of answerable questions where at least one gold title appears in top-K chunks |\n",
        "| MRR | Mean Reciprocal Rank of first matching chunk (0 if not found in top-K) |\n",
        "| Answer F1 | Token-level F1 between generated answer and gold answer |\n",
        "| Exact Match | Strict lower-cased match between generated and gold answer |\n",
        "| Citation Precision | Fraction of [chunk_id] citations that exist in the retrieved set |\n",
        "| Abstention Accuracy | Fraction of questions where system correctly chose to answer or abstain |\n",
    ]

    REPORT.write_text("".join(sections))
    print(f"Report written to {REPORT}")


if __name__ == "__main__":
    main()
